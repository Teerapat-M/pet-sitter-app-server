-- ---------------------------------------------------------------------------
-- bookings + booking_pets + payments
-- Live columns after duration_hours → duration/duration_unit and
-- booking_date → start_date/end_date (54c56ce, 6e9cd86, sql/payout-option-v1.sql).
-- ---------------------------------------------------------------------------
CREATE TABLE public.bookings (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  owner_id uuid NOT NULL REFERENCES public.users (id),
  sitter_id uuid NOT NULL REFERENCES public.users (id),
  start_date date NOT NULL,
  end_date date NOT NULL,
  start_time time NOT NULL,
  end_time time NOT NULL,
  duration integer NOT NULL,
  duration_unit varchar(16) NOT NULL,
  payment_method varchar(10),
  transaction_no varchar(32),
  contact_name varchar,
  contact_email varchar,
  contact_phone varchar,
  additional_message text,
  total_price numeric(12, 2) NOT NULL,
  status varchar(32) NOT NULL DEFAULT 'waiting_confirm',
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT bookings_payment_method_check
    CHECK (payment_method IS NULL OR payment_method IN ('cash', 'stripe')),
  CONSTRAINT bookings_duration_unit_check
    CHECK (duration_unit IN ('hours', 'Day')),
  CONSTRAINT bookings_status_check CHECK (
    status IN (
      'waiting_confirm',
      'waiting_service',
      'in_service',
      'success',
      'cancelled'
    )
  ),
  CONSTRAINT bookings_date_range_check CHECK (end_date >= start_date)
);

CREATE UNIQUE INDEX bookings_transaction_no_unique_idx
  ON public.bookings (transaction_no)
  WHERE transaction_no IS NOT NULL;

CREATE INDEX bookings_sitter_id_created_at_idx
  ON public.bookings (sitter_id, created_at DESC);

CREATE INDEX bookings_owner_id_created_at_idx
  ON public.bookings (owner_id, created_at DESC);

CREATE INDEX bookings_sitter_busy_idx
  ON public.bookings (sitter_id, start_date, end_date)
  WHERE status IN ('waiting_confirm', 'waiting_service', 'in_service');

CREATE SEQUENCE public.booking_transaction_no_seq
  START WITH 1
  INCREMENT BY 1;

CREATE OR REPLACE FUNCTION public.next_transaction_no()
RETURNS text
LANGUAGE plpgsql
AS $$
DECLARE
  today text := to_char(now() AT TIME ZONE 'Asia/Bangkok', 'YYYYMMDD');
  running int;
BEGIN
  running := nextval('public.booking_transaction_no_seq');
  RETURN format('TX-%s-%s', today, lpad(running::text, 4, '0'));
END;
$$;

