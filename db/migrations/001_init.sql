-- ---------------------------------------------------------------------------
-- users — id matches Supabase auth.users.id (app copies the UUID; no FK
-- evidenced in queries, omitted so this file runs on vanilla Postgres too)
-- ---------------------------------------------------------------------------
CREATE TABLE public.users (
  id uuid PRIMARY KEY,
  name varchar(20),
  email varchar(255) NOT NULL,
  phone varchar(10) NOT NULL,
  id_number varchar(13),
  date_of_birth date,
  avatar_url text,
  is_admin boolean NOT NULL DEFAULT false,
  is_verified boolean NOT NULL DEFAULT false,
  is_banned boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT users_email_unique UNIQUE (email),
  CONSTRAINT users_phone_unique UNIQUE (phone)
);

CREATE INDEX users_created_at_idx ON public.users (created_at DESC);

